#!/usr/bin/env python3
"""Offline compiler for the *relative-time subset* of the macro language (wait/gap/taplen/tap/hold/shot/mark).
The harness (mgba_trace --macro) also understands waitstable/waitchange/monkey, which need the emulator, so those macros
are resolved by `run_trace.py --from-macro` instead (it writes traces/inputs/<name>.txt). Kept for quick inspection.

Compile a relative-time macro script into the absolute-frame input format read by mgba_trace.

usage: mkinput.py IN.macro [OUT.txt]      (OUT defaults to IN with .txt; '-' = stdout)

Macro syntax (one directive per line, '#' comments, blank lines ignored):
  wait N               advance N frames
  gap N                set the idle gap (frames) that follows every tap (default 14)
  taplen N             set the number of frames a tap is held (default 4)
  tap BTN [xN]         press BTN (A B SELECT START UP DOWN LEFT RIGHT, or A+B) for taplen frames, N times,
                       each followed by `gap` idle frames
  hold BTN N           hold BTN for N frames, then release
  shot [name]          screenshot now
  mark text...         annotation copied into marks_<scenario>.tsv
Output lines: '<frame> <BUTTONS|->', '<frame> shot name', '<frame> mark text'
(the format is documented in tools/trace/mgba_trace.c and docs/research/dynamic_tracing.md).
The generated file contains a header comment with the total frame count needed.
"""
import re
import sys


def compile_macro(text):
    out = []
    frame = 0
    gap = 14
    taplen = 4
    for ln, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split(None, 1)
        cmd = parts[0].lower()
        arg = parts[1].strip() if len(parts) > 1 else ""
        if cmd == "wait":
            frame += int(arg)
        elif cmd == "gap":
            gap = int(arg)
        elif cmd == "taplen":
            taplen = int(arg)
        elif cmd == "tap":
            m = re.match(r"(\S+)(?:\s+x(\d+))?$", arg)
            if not m:
                raise SystemExit(f"line {ln}: bad tap")
            for _ in range(int(m.group(2) or 1)):
                out.append(f"{frame} {m.group(1)}")
                out.append(f"{frame + taplen} -")
                frame += taplen + gap
        elif cmd == "hold":
            b, n = arg.split()
            out.append(f"{frame} {b}")
            out.append(f"{frame + int(n)} -")
            frame += int(n) + gap
        elif cmd == "shot":
            out.append(f"{frame} shot {arg}".rstrip())
        elif cmd == "mark":
            out.append(f"{frame} mark {arg}")
        else:
            raise SystemExit(f"line {ln}: unknown directive {cmd!r}")
    return out, frame


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else re.sub(r"\.macro$", "", src) + ".txt"
    lines, total = compile_macro(open(src).read())
    body = f"# generated by tools/trace/mkinput.py from {src.rsplit('/', 1)[-1]} - do not edit\n# last scripted frame: {total}\n" + "\n".join(lines) + "\n"
    if dst == "-":
        sys.stdout.write(body)
    else:
        open(dst, "w").write(body)


if __name__ == "__main__":
    main()
