#!/usr/bin/env python3
"""Coverage growth per scenario (cumulative, in the order of traces/scenarios.tsv).

For every scenario: executed ROM instruction starts, how many of them were new (not executed by any earlier scenario in the table), the
cumulative union, ROM banks that ran code, and - against the region map of a config dir - the cumulative number of *executed instruction
bytes* and of code bytes that sit in regions whose every instruction start has been executed ("fully executed regions").  Writes
traces/growth.md (deterministic).  Inputs: traces/scenarios.tsv, traces/coverage_<scenario>.tsv, the config dir (default: config).

usage: growth.py [--config-dir DIR] [--out FILE]
"""
import argparse
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import apply_coverage as ac  # noqa: E402
import sm83  # noqa: E402


def read_cov(path):
    s = set()
    for ln in path.read_text().splitlines():
        if not ln or ln.startswith("#"):
            continue
        f = ln.split("\t")
        if len(f[0]) == 2 and f[0] not in ("WRAM", "HRAM"):
            s.add((int(f[0], 16), int(f[1], 16)))
    return s


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config-dir", default=str(ROOT / "config"))
    ap.add_argument("--out", default=str(ROOT / "traces" / "growth.md"))
    a = ap.parse_args(argv)
    rom = (ROOT / "baserom.gbc").read_bytes()
    cfg, table = ac.load_config(Path(a.config_dir), rom)
    names = []
    desc = {}
    for ln in (ROOT / "traces" / "scenarios.tsv").read_text().splitlines():
        if not ln or ln.startswith("#") or ln.startswith("name\t"):
            continue
        f = ln.split("\t")
        names.append(f[0])
        desc[f[0]] = f[5] if len(f) > 5 else ""
    # region structure
    start_region = {}                    # (bank, addr) -> region index
    regions = []
    ilen = {}
    for b in range(len(rom) // ac.BANK_SIZE):
        win = rom[b * ac.BANK_SIZE:(b + 1) * ac.BANK_SIZE]
        base = 0 if b == 0 else 0x4000
        for r in cfg.regions[b]:
            if r.kind != "code":
                continue
            starts, _inl, _t = ac.region_starts(r, rom, table)
            idx = len(regions)
            regions.append([len(starts), 0, r.size])
            for st in starts:
                start_region[(b, st)] = idx
                ilen[(b, st)] = sm83.decode(win, st - base, st).length
    seen = set()
    exec_bytes = 0
    full_bytes = 0
    rows = []
    banks = set()
    for n in names:
        p = ROOT / "traces" / ("coverage_%s.tsv" % n)
        if not p.exists():
            continue
        cov = read_cov(p)
        new = cov - seen
        for k in new:
            idx = start_region.get(k)
            if idx is not None:
                exec_bytes += ilen[k]
                reg = regions[idx]
                reg[1] += 1
                if reg[1] == reg[0]:
                    full_bytes += reg[2]
        seen |= cov
        banks |= {b for b, _ in cov}
        rows.append((n, len(cov), len(new), len(seen), len(banks), exec_bytes, full_bytes))
    tot_code = sum(r[2] for r in regions)
    L = ["# Dynamic coverage growth per scenario", "",
         "Generated by `tools/trace/growth.py` (do not edit). Scenarios in the order of `traces/scenarios.tsv`; *new* = instruction starts not executed by any",
         "earlier row; *code bytes in fully executed regions* and *executed instruction bytes* use the region map of `%s` (%d code bytes in %d regions,"
         % ("config", tot_code, len(regions)),
         "inline convention data not counted). Coverage is evidence of code; absence proves nothing.", "",
         "| scenario | starts | new | cumulative starts | banks | executed insn bytes | code bytes in fully executed regions |", "|---|---:|---:|---:|---:|---:|---:|"]
    for r in rows:
        L.append("| %s | %d | %d | %d | %d | %d | %d |" % r)
    L.append("")
    Path(a.out).write_text("\n".join(L) + "\n")
    print("wrote %s (%d scenarios; cumulative %d starts, %d executed insn bytes, %d bytes in fully executed regions of %d)" % (
        a.out, len(rows), len(seen), exec_bytes, full_bytes, tot_code))
    return 0


if __name__ == "__main__":
    sys.exit(main())
