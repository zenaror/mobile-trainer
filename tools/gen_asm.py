#!/usr/bin/env python3
"""Production source generator: ROM bytes + config/ tables -> RGBDS sources.

    gen_asm.py [regen]  [--config DIR] [--out DIR] [--rom FILE] [--fast] [--strict] [-q]
    gen_asm.py verify   [--config DIR] [--rom FILE] [--keep DIR] [--strict]
    gen_asm.py check    [--config DIR] [--rom FILE] [--strict]

regen   generate src/bankNN.asm + src/ram.inc from the ROM and config/, run the
        internal structural round-trip check, then (unless --fast) assemble and
        link the result in a temp dir and compare it with the ROM; the files in
        --out are written only if every check passes.
verify  generate into a temp dir (never touches --out), assemble + link, compare
        with the ROM and print any differences mapped to regions.
check   generate in memory and run the structural checks only (no files, no rgbasm).

The generated code is byte-exact by construction: every emitted line is
re-parsed / cross-checked against the ROM bytes and every name substituted for
a number is checked to have exactly that numeric value.  See docs/FORMATS.md.
"""
