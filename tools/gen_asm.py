def load_model(rom_path: Optional[str] = None, cfgdir: Optional[str] = None, hw_path: Optional[str] = None,
               strict: bool = False, extra_xrefs=(), rom: Optional[bytes] = None, macros: bool = True):
    """Load ROM + config and build the Model.  Returns (model, diag)."""
    rom_path = rom_path or os.path.join(ROOT, 'baserom.gbc')
    cfgdir = cfgdir or os.path.join(ROOT, 'config')
    if rom is None:
        if not os.path.exists(rom_path):
            raise GenError('missing ROM %s (run `make baserom`)' % rom_path)
        with open(rom_path, 'rb') as fh:
            rom = fh.read()
    if len(rom) < BANK_SIZE or len(rom) % BANK_SIZE:
        raise GenError('ROM size %d is not a positive multiple of 16 KiB' % len(rom))
    hw = mtcfg.load_hardware(hw_path)
    diag = Diag(strict)
    cfg = mtcfg.load_config(cfgdir, len(rom) // BANK_SIZE, hw, diag, extra_xrefs)
    diag.raise_if_errors()
    model = Model(rom, cfg, hw, os.path.basename(rom_path), strict, macros)
    return model, diag


def write_files(files: Dict[str, str], outdir: str) -> int:
    os.makedirs(outdir, exist_ok=True)
    changed = 0
    for name, text in sorted(files.items()):
        path = os.path.join(outdir, name)
        if os.path.exists(path):
            with open(path, encoding='utf-8') as fh:
                if fh.read() == text:
                    continue
        with open(path, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        changed += 1
    return changed


def assemble(files: Dict[str, str], workdir: str, rom_dir: str, jobs: Optional[int] = None) -> Tuple[str, List[str]]:
    """Write `files` to workdir/src, assemble each bank and link.  Returns (rom_path, log)."""
    src, obj = os.path.join(workdir, 'src'), os.path.join(workdir, 'obj')
    os.makedirs(src, exist_ok=True)
    os.makedirs(obj, exist_ok=True)
    write_files(files, src)
    banks = sorted(n for n in files if n.endswith('.asm'))

    def one(name):
        o = os.path.join(obj, name[:-4] + '.o')
        p = subprocess.run(['rgbasm', '-I', src, '-I', rom_dir, '-I', ROOT, '-o', o, os.path.join(src, name)],
                           capture_output=True, text=True, cwd=workdir)
        return name, o, p

    objs, log = [], []
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs or min(16, os.cpu_count() or 4)) as ex:
        for name, o, p in ex.map(one, banks):
            if p.returncode:
                raise GenError('rgbasm failed on %s:\n%s' % (name, p.stderr[:3000]))
            if p.stderr.strip():
                log.append('%s: %s' % (name, p.stderr.strip()[:500]))
            objs.append(o)
    rom = os.path.join(workdir, 'out.gbc')
    p = subprocess.run(['rgblink', '-p', '0x00', '-n', os.path.join(workdir, 'out.sym'), '-o', rom] + objs, capture_output=True, text=True, cwd=workdir)
    if p.returncode:
        raise GenError('rgblink failed:\n%s' % p.stderr[:3000])
    return rom, log


def assemble_and_compare(files, rom: bytes, rom_path: str, cfgdir: str, workdir: str, quiet=False) -> bool:
    import compare_rom
    built_path, log = assemble(files, workdir, os.path.dirname(os.path.abspath(rom_path)))
    for line in log[:10]:
        print('rgbasm warning: ' + line, file=sys.stderr)
    with open(built_path, 'rb') as fh:
        built = fh.read()
    return compare_rom.compare(rom, built, cfgdir, out=(lambda *a, **k: None) if quiet else print)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('mode', nargs='?', default='regen', choices=('regen', 'verify', 'check'))
    ap.add_argument('--config', default=os.path.join(ROOT, 'config'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'src'))
    ap.add_argument('--rom', default=os.path.join(ROOT, 'baserom.gbc'))
    ap.add_argument('--fast', action='store_true', help='regen: skip the rgbasm/rgblink check')
    ap.add_argument('--strict', action='store_true', help='treat config warnings as errors')
    ap.add_argument('--xrefs', action='append', default=[], help='additional xrefs file (same format as config/xrefs.tsv)')
    ap.add_argument('--keep', help='verify: keep the temp build in this directory')
    ap.add_argument('--no-macros', action='store_true', help='emit `call FarCall` + dw + db instead of the farcall macros')
    ap.add_argument('-q', '--quiet', action='store_true')
    a = ap.parse_args(argv)

    try:
        model, diag = load_model(a.rom, a.config, None, a.strict, a.xrefs, macros=not a.no_macros)
        for w in (diag.warnings + model.diag.warnings)[:25]:
            print('warning: ' + w, file=sys.stderr)
        files = model.generate()
    except GenError as e:
        print('error: %s' % e, file=sys.stderr)
        return 1

    if a.mode == 'check':
        if not a.quiet:
            print('check OK: %d banks generated in memory, structural round-trip passed' % model.nbanks)
        return 0

    with open(a.rom, 'rb') as fh:
        rom = fh.read()
    if a.mode == 'verify' or not a.fast:
        tmp = a.keep or tempfile.mkdtemp(prefix='mtgen_')
        try:
            os.makedirs(tmp, exist_ok=True)
            ok = assemble_and_compare(files, rom, a.rom, a.config, tmp, quiet=(a.mode == 'regen'))
        except GenError as e:
            print('error: %s' % e, file=sys.stderr)
            ok = False
        finally:
            if not a.keep:
                shutil.rmtree(tmp, ignore_errors=True)
        if not ok:
            print('error: generated sources do not rebuild the ROM byte-identically%s' % (
                '; nothing was written' if a.mode == 'regen' else ''), file=sys.stderr)
            return 1
        if a.mode == 'verify':
            stale = []
            for name, text in files.items():
                p = os.path.join(a.out, name)
                if not os.path.exists(p) or open(p, encoding='utf-8').read() != text:
                    stale.append(name)
            if stale:
                print('note: %d file(s) in %s differ from the generated sources (run `make regen`)' % (
                    len(stale), os.path.relpath(a.out, ROOT) if a.out.startswith(ROOT) else a.out))
            return 0

    changed = write_files(files, a.out)
    if not a.quiet:
        print('regen OK: %d banks, %d file(s) rewritten in %s%s' % (
            model.nbanks, changed, a.out, '' if a.fast else ' (assemble+link check passed)'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
