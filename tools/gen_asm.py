@dataclass
class Label:
    name: str
    origin: str          # 'symbol' | 'region' | 'generic'
    loc: str = ''


def hexb(v: int) -> str:
    return '$%02X' % v


def hexw(v: int) -> str:
    return '$%04X' % v


class BankOut:
    """Collects the lines of one bank and checks that the emitted bytes tile the bank exactly."""

    def __init__(self, model: 'Model', bank: int):
        self.model = model
        self.bank = bank
        self.lines: List[str] = []
        self.pos = 0

    def line(self, text: str = ''):
        if not text and (not self.lines or not self.lines[-1]):
            return                      # never two blank lines in a row
        self.lines.append(text)

    def emit(self, text: str, claim: bytes):
        m = self.model
        absoff = self.bank * BANK_SIZE + self.pos
        if m.rom[absoff:absoff + len(claim)] != claim:
            raise GenError('internal: line %r does not match ROM bytes at %02X:%04X' % (
                text, self.bank, self.pos + (0 if self.bank == 0 else 0x4000)))
        m.verify_line(text, claim, absoff)
        self.lines.append(text)
        self.pos += len(claim)


class Model:
    """Everything the emitter needs: decoded code, label tables, cross references."""

    def __init__(self, rom: bytes, cfg: mtcfg.Config, hw: mtcfg.Hardware, incbin: str = 'baserom.gbc', strict: bool = False,
                 macros: bool = True):
        if len(rom) < BANK_SIZE or len(rom) % BANK_SIZE:
            raise GenError('ROM size %d is not a positive multiple of 16 KiB' % len(rom))
        self.rom = rom
        self.macros = macros            # emit `farcall` / `farcall_raw` (constants/macros.inc) instead of call + dw + db
        self._fc = False                # cached far-call convention (False = not looked up yet)
        self.cfg = cfg
        self.hw = hw
        self.incbin = incbin
        self.nbanks = len(rom) // BANK_SIZE
        self.regions = cfg.regions
        self.diag = Diag(strict)         # --strict: warnings raised while building the model (RAM name shadowing, convention entries) are errors
        self.insns: Dict[Tuple[int, int], List[Tuple[int, sm83.Insn]]] = {}
        self.bound: Dict[int, set] = {b: set() for b in range(self.nbanks)}
        self.labels: Dict[int, Dict[int, List[Label]]] = {b: {} for b in range(self.nbanks)}
        self.name_loc: Dict[str, tuple] = {}     # name -> (bank, addr) | ('const',)
        self.name_val: Dict[str, int] = {}       # label name -> runtime address
        self.consts: List[mtcfg.Symbol] = []
        self.ramcodes: List[Region] = []
        self.union: Dict[Tuple[int, int], str] = {}
        self.want: Dict[Tuple[int, int], set] = defaultdict(set)
        self.xref: Dict[Tuple[int, int, str], tuple] = {}
        self.label_addrs: Dict[int, List[int]] = {}
        self.ram_sorted: List[mtcfg.RamVar] = []
        self.ram_exact: Dict[int, mtcfg.RamVar] = {}
        self.stats: Dict[str, int] = defaultdict(int)
        # inline-data conventions (config/conventions.tsv)
        self.conv_table = conv.ConvTable(cfg.conventions, {(x.bank, x.addr): (x.tbank, x.taddr) for x in cfg.xrefs
                                                           if x.kind == 'branch' and x.tbank != 'RAM'})
        self.inline_adopt: Dict[Tuple[int, int], conv.InlineData] = {}      # (bank, addr) -> inline bytes held by a `data` region
        self.inline_cover: Dict[int, Dict[int, tuple]] = {b: {} for b in range(self.nbanks)}   # addr -> (site, label allowed)
        self.inline_slots: Dict[Tuple[int, int], str] = {}                  # (bank, slot addr) -> layout
        self._build()

    # ------------------------------------------------------------------ build
    def _build(self):
        self._check_zero_regions()
        self._decode()
        self._check_conventions()
        self._index_ramcode()
        self._index_ram()
        self._collect_labels()
        self._check_macro_names()
        self.diag.raise_if_errors()
        self._resolve_xrefs()
        self._collect_refs()
        self.diag.raise_if_errors()
        self._finalize_labels()
        self._check_xref_targets()
        self.diag.raise_if_errors()
        for b in range(self.nbanks):
            self.label_addrs[b] = sorted(self.labels[b])

    def region_at(self, bank: int, addr: int) -> Optional[Region]:
        return mtcfg.region_at(self.regions[bank], addr)

    def run_addr(self, bank: int, addr: int) -> int:
        r = self.region_at(bank, addr)
        if r is not None and r.kind == 'ramcode':
            return r.runaddr + (addr - r.start)
        return addr

    def bytes_of(self, r: Region) -> bytes:
        return self.rom[r.off:r.off + r.size]

    @staticmethod
    def cite(bank: int, addr: int) -> str:
        return '%02X:%04X' % (bank, addr)

    def _check_zero_regions(self):
        for b in range(self.nbanks):
            for r in self.regions[b]:
                if r.kind == 'zero' and any(self.bytes_of(r)):
                    first = next(i for i, v in enumerate(self.bytes_of(r)) if v)
                    self.diag.error(r.loc, "zero region %02X:%04X-%04X contains a non-zero byte at %02X:%04X"
                                    % (b, r.start, r.end, b, r.start + first))
        self.diag.raise_if_errors()

    def _decode(self):
        for b in range(self.nbanks):
            for r in self.regions[b]:
                if r.kind not in ('code', 'ramcode'):
                    continue
                addr0 = r.runaddr if r.kind == 'ramcode' else r.start
                res = conv.scan(self.bytes_of(r), addr0, r.start, b, r.kind, self.conv_table)
                if res.cross is not None:
                    at, op, full = res.cross
                    self.diag.error(r.loc, '%s region %02X:%04X-%04X: instruction at %02X:%04X (opcode $%02X, %d bytes) '
                                    'crosses the region end' % (r.kind, b, r.start, r.end, b, at, op, full))
                bound = self.bound[b]
                for sa, it in res.items:
                    if it.flow == 'inline':
                        self._register_inline(b, it)
                    else:
                        bound.add(sa)
                self.insns[(b, r.idx)] = res.items
                if res.overflow is not None:
                    self._inline_overflow(r, res.overflow)
        self.diag.raise_if_errors()

    def _register_inline(self, b: int, it: conv.InlineData, label_at_start: bool = False):
        for k in range(it.length):
            self.inline_cover[b][it.slot + k] = (it.site, label_at_start and k == 0)
        self.inline_slots[(b, it.slot)] = it.conv.layout
        st = self.stats
        st['inline_sites'] += 1
        st['inline_bytes'] += it.length
        st['inline_' + it.conv.layout] += 1

    def _inline_overflow(self, r: Region, ov: conv.Overflow):
        """A convention call whose inline bytes do not fit into the rest of its code region."""
        b = r.bank
        sa, ins = self.insns[(b, r.idx)][ov.index]
        c = ov.conv
        e = sa + ins.length
        what = '%s at %02X:%04X (%s, convention %02X:%04X %s [%s])' % (
            ins.text(), b, sa, ins.raw.hex(), c.bank, c.addr, c.layout, c.loc)
        if ov.have == 0 and r.kind == 'code' and r.idx + 1 < len(self.regions[b]):
            nxt = self.regions[b][r.idx + 1]
            if nxt.start == e and nxt.kind == 'data' and nxt.size >= c.size:
                # tolerated: the bytes right after the call were classified as a `data` region of their own
                it = conv.InlineData(e, e, self.rom[nxt.off:nxt.off + c.size], c, sa)
                self.inline_adopt[(b, e)] = it
                self._register_inline(b, it, label_at_start=True)
                self.stats['inline_adopted'] += 1
                return
        end = e + c.size
        hdr = 'convention call %s: its %d inline byte(s) at %02X:%04X-%04X ' % (what, c.size, b, e, end)
        if ov.have:
            self.diag.error(r.loc, hdr + 'cross the end of the %s region %04X-%04X: move that region edge to $%04X '
                            '(inline data must stay inside one code region), or end the region before the call at $%04X'
                            % (r.kind, r.start, r.end, end, sa))
        elif r.idx + 1 >= len(self.regions[b]):
            self.diag.error(r.loc, hdr + 'would lie beyond the end of bank %02X: end the %s region %04X-%04X before '
                            'the call at $%04X' % (b, r.kind, r.start, r.end, sa))
        else:
            nxt = self.regions[b][r.idx + 1]
            self.diag.error(r.loc, hdr + 'start at the next region %04X-%04X (kind %s, %s): move the end of this %s '
                            'region %04X-%04X to $%04X so the inline bytes belong to it%s' % (
                                nxt.start, nxt.end, nxt.kind, nxt.loc, r.kind, r.start, r.end, end,
                                '' if r.kind == 'code' else '; ramcode never adopts a following data region'))

    def _check_conventions(self):
        for c in self.cfg.conventions:
            r = self.region_at(c.bank, c.addr)
            if r is not None and r.kind == 'code' and c.addr not in self.bound[c.bank]:
                self.diag.warn(c.loc, 'convention entry %02X:%04X is not on an instruction boundary of the code region '
                               '%04X-%04X (%s)' % (c.bank, c.addr, r.start, r.end, r.loc))

    def _index_ramcode(self):
        self.ramcodes = [r for b in range(self.nbanks) for r in self.regions[b] if r.kind == 'ramcode']
        marked = set()
        for i, a in enumerate(self.ramcodes):
            for c in self.ramcodes[i + 1:]:
                if a.runbank != c.runbank or not (a.runaddr < c.run_end and c.runaddr < a.run_end):
                    continue
                if a.runaddr != c.runaddr:
                    self.diag.error(c.loc, 'ramcode runtime range $%04X-$%04X partially overlaps $%04X-$%04X of %s: '
                                    'overlays must start at the same runaddr' % (
                                        c.runaddr, c.run_end, a.runaddr, a.run_end, a.loc))
                    continue
                marked.add((a.bank, a.idx))
                marked.add((c.bank, c.idx))
        for r in self.ramcodes:
            if (r.bank, r.idx) in marked:
                nm = 'RAMOVL_%04X' % r.runaddr + ('_B%d' % r.runbank if r.runbank is not None else '')
                self.union[(r.bank, r.idx)] = nm

    def ram_targets(self, addr: int) -> List[Region]:
        return [r for r in self.ramcodes if r.runaddr <= addr < r.run_end]

    def _index_ram(self):
        seen = {}
        for v in self.cfg.ram:
            if v.name in seen:
                self.diag.error(v.loc, 'RAM name %s already defined at %s' % (v.name, seen[v.name]))
                continue
            seen[v.name] = v.loc
            if v.addr in self.hw.io and (0xFF00 <= v.addr <= 0xFF7F or v.addr == 0xFFFF):
                self.diag.warn(v.loc, 'address $%04X already has the hardware name %s (hardware name wins)'
                               % (v.addr, self.hw.io[v.addr]))
            self.name_loc[v.name] = ('ram', v.addr)
            self.ram_exact.setdefault(v.addr, v)
        self.ram_sorted = sorted(self.cfg.ram, key=lambda v: (v.addr, v.name))
        self._ram_starts = [v.addr for v in self.ram_sorted]
        self._ram_maxsize = max([v.size for v in self.ram_sorted] or [1])

    def ram_expr(self, addr: int) -> Optional[Tuple[str, int]]:
        """Name expression for a RAM address from config/ram: (text, value) or None."""
        v = self.ram_exact.get(addr)
        if v is not None:
            return v.name, addr
        i = bisect.bisect_right(self._ram_starts, addr) - 1
        while i >= 0:
            v = self.ram_sorted[i]
            if v.addr <= addr < v.addr + v.size:
                return '%s + %d' % (v.name, addr - v.addr), addr
            if v.addr + self._ram_maxsize <= addr:      # nothing that far away can enclose it
                break
            i -= 1
        return None

    # ----------------------------------------------------------------- labels
    def add_label(self, bank: int, addr: int, name: str, origin: str, loc: str):
        r = self.region_at(bank, addr)
        if r is None:
            self.diag.error(loc, 'label %s: address %02X:%04X is outside the bank window' % (name, bank, addr))
            return
        cov = self.inline_cover[bank].get(addr)
        if cov is not None and not cov[1]:
            self.diag.error(loc, 'label %s at %02X:%04X is inside the inline data of the convention call at %02X:%04X: '
                            'inline bytes are data, nothing can be labelled there' % (name, bank, addr, bank, cov[0]))
            return
        if r.kind in ('code', 'ramcode') and addr not in self.bound[bank]:
            self.diag.error(loc, 'label %s at %02X:%04X is not on an instruction boundary of the %s region %04X-%04X '
                            '(split the region or fix the address)' % (name, bank, addr, r.kind, r.start, r.end))
            return
        if r.kind in ('words', 'ptrtable') and (addr - r.start) % 2:
            self.diag.error(loc, 'label %s at %02X:%04X is not word-aligned inside the %s region %04X-%04X'
                            % (name, bank, addr, r.kind, r.start, r.end))
            return
        prev = self.name_loc.get(name)
        if prev is not None:
            if prev == (bank, addr):
                return
            self.diag.error(loc, 'label collision: name %s already used (%s)%s' % (
                name, {'const': 'const symbol', 'ram': 'RAM variable'}.get(prev[0]) or self.cite(*prev),
                '; overlays of one bank sharing a runaddr need distinct symbols' if origin == 'generic' else ''))
            return
        ra = self.run_addr(bank, addr)
        m = mtcfg.GENERIC.match(name)
        if m and origin != 'generic' and (int(m.group(2), 16), int(m.group(3), 16)) != (bank, ra):
            self.diag.error(loc, 'name %s looks like a generic name for %s:%s but labels %02X:%04X; '
                            'use a different name or the matching address' % (name, m.group(2), m.group(3), bank, ra))
            return
        self.name_loc[name] = (bank, addr)
        self.name_val[name] = ra
        self.labels[bank].setdefault(addr, []).append(Label(name, origin, loc))

    def _collect_labels(self):
        for b in range(self.nbanks):
            for s in self.cfg.symbols.get(b, ()):
                if s.type == 'const':
                    if s.name in self.name_loc:
                        self.diag.error(s.loc, 'name %s already used' % s.name)
                        continue
                    self.name_loc[s.name] = ('const',)
                    self.consts.append(s)
                else:
                    self.add_label(b, s.addr, s.name, 'symbol', s.loc)
        for b in range(self.nbanks):
            for r in self.regions[b]:
                if r.label:
                    self.add_label(b, r.start, r.label, 'region', r.loc)

    def named_at(self, loc) -> Optional[str]:
        for lab in self.labels[loc[0]].get(loc[1], ()):
            if lab.origin != 'generic':
                return lab.name
        return None

    def name_at(self, loc) -> Optional[str]:
        labs = self.labels[loc[0]].get(loc[1])
        return labs[0].name if labs else None

    def has_label(self, loc) -> bool:
        return loc[1] in self.labels[loc[0]]

    # ------------------------------------------------------------ target rules
    def resolve_target(self, src_bank: int, src: Region, target: int) -> Optional[Tuple[int, int]]:
        """Map a CPU address referenced from `src` to ROM coordinates (bank, storage address), or None.

        ROM0 is always bank 0; ROMX addresses belong to the referencing bank when it is itself a
        ROMX bank (code in bank N cannot switch itself away); a reference from ROM0 or from RAM code
        into 4000-7FFF has no defined bank.  RAM addresses resolve only into a unique ramcode region.
        """
        if src.kind == 'ramcode' and src.runaddr <= target < src.run_end:
            return src_bank, src.start + (target - src.runaddr)
        if target < 0x8000:
            if target < 0x4000:
                loc = (0, target)
            elif src_bank != 0 and src.kind != 'ramcode':
                loc = (src_bank, target)
            else:
                return None
            r = self.region_at(*loc)
            if r is not None and r.kind == 'ramcode':
                return None        # bytes stored here run elsewhere: the ROM address is not a label
            return loc
        hits = self.ram_targets(target)
        if len(hits) == 1:
            h = hits[0]
            return h.bank, h.start + (target - h.runaddr)
        return None

    def _want(self, loc, kind: str, force: bool = False, where: str = '') -> bool:
        tb, ta = loc
        if self.has_label(loc):
            return True
        r = self.region_at(tb, ta)
        if r is None:
            return False
        if r.kind in ('code', 'ramcode'):
            if ta in self.bound[tb]:
                self.want[loc].add(kind)
                return True
            self.stats['targets_mid_instruction'] += 1
            return False
        if force:
            if r.kind in ('words', 'ptrtable') and (ta - r.start) % 2:
                self.diag.error(where, 'xref target %02X:%04X is not word-aligned inside its %s region' % (tb, ta, r.kind))
                return False
            self.want[loc].add(kind)
            return True
        return False

    def _insn_at(self, bank: int, addr: int):
        r = self.region_at(bank, addr)
        if r is None or r.kind not in ('code', 'ramcode') or addr not in self.bound[bank]:
            return None, None
        lst = self.insns[(bank, r.idx)]
        i = bisect.bisect_left(lst, addr, key=lambda t: t[0])
        return r, lst[i][1]

    def _resolve_xrefs(self):
        for x in self.cfg.xrefs:
            where = x.loc
            key = (x.bank, x.addr, x.kind)
            if key in self.xref:
                self.diag.error(where, 'duplicate xref for %02X:%04X %s' % (x.bank, x.addr, x.kind))
                continue
            value = None
            kind = 'imm'
            if x.kind == 'word':
                r = self.region_at(x.bank, x.addr)
                slot = self.inline_slots.get((x.bank, x.addr))
                if slot == 'inline_dw':
                    o = x.bank * BANK_SIZE + (x.addr - mtcfg.window(x.bank)[0])
                    value = self.rom[o] | (self.rom[o + 1] << 8)
                elif slot == 'farptr':
                    self.diag.error(where, 'xref word: %02X:%04X is the pointer of a farptr convention slot; it is labelled '
                                    'automatically when a label exists at exactly (bank byte, address)' % (x.bank, x.addr))
                    continue
                elif r is None or r.kind not in ('words', 'ptrtable') or (x.addr - r.start) % 2:
                    self.diag.error(where, 'xref word: %02X:%04X is not a word slot of a words/ptrtable region '
                                    'or an inline_dw convention slot' % (x.bank, x.addr))
                    continue
                else:
                    value = self.rom[r.off + (x.addr - r.start)] | (self.rom[r.off + (x.addr - r.start) + 1] << 8)
            else:
                r, ins = self._insn_at(x.bank, x.addr)
                if ins is None:
                    self.diag.error(where, 'xref: no instruction starts at %02X:%04X (stale xref?)' % (x.bank, x.addr))
                    continue
                if x.kind == 'branch':
                    value = ins.target
                    kind = 'call' if ins.flow in CALL_FLOWS else 'jump'
                elif x.kind == 'imm' and ins.imm16_kind == 'imm':
                    value = ins.imm16
                elif x.kind == 'mem' and ins.imm16_kind == 'mem':
                    value = ins.imm16
                if value is None:
                    self.diag.error(where, 'xref: instruction at %02X:%04X (%s) has no %s operand' % (
                        x.bank, x.addr, ins.text(), x.kind))
                    continue
            if x.taddr != value:
                self.diag.error(where, 'xref target address $%04X differs from the operand value $%04X at %02X:%04X: '
                                'a name must not change bytes' % (x.taddr, value, x.bank, x.addr))
                continue
            if x.tbank == 'RAM':
                ex = self.ram_expr(x.taddr)
                if ex is None:
                    self.diag.error(where, 'xref target RAM $%04X has no name in config/ram' % x.taddr)
                    continue
                self.xref[key] = ('ram', ex)
                continue
            if x.taddr >= 0x8000:
                hits = [h for h in self.ram_targets(x.taddr) if h.bank == x.tbank]
                if len(hits) != 1:
                    self.diag.error(where, 'xref target $%04X: expected exactly one ramcode region in bank %02X, found %d'
                                    % (x.taddr, x.tbank, len(hits)))
                    continue
                loc = (x.tbank, hits[0].start + (x.taddr - hits[0].runaddr))
            else:
                lo, hi = mtcfg.window(x.tbank)
                if not lo <= x.taddr < hi:
                    self.diag.error(where, 'xref target $%04X is not inside bank %02X window' % (x.taddr, x.tbank))
                    continue
                loc = (x.tbank, x.taddr)
            if self.run_addr(*loc) != x.taddr:
                self.diag.error(where, 'xref target %02X:%04X is stored in a ramcode region that runs at $%04X, not $%04X'
                                % (loc[0], loc[1], self.run_addr(*loc), x.taddr))
                continue
            if not self._want(loc, kind, True, where):
                self.diag.error(where, 'xref target %02X:%04X cannot be labelled (mid-instruction?)' % loc)
                continue
            self.xref[key] = ('loc', loc)
            self.stats['xrefs'] += 1

    def _check_xref_targets(self):
        for key, val in self.xref.items():
            if val[0] == 'loc' and not self.has_label(val[1]):
                raise GenError('internal: xref target %02X:%04X has no label' % val[1])

    def _collect_refs(self):
        for (b, ridx), lst in self.insns.items():
            r = self.regions[b][ridx]
            for sa, ins in lst:
                if ins.flow == 'inline':
                    self._collect_inline(b, ins)
                    continue
                if ins.target is None or (b, sa, 'branch') in self.xref:
                    continue
                loc = self.resolve_target(b, r, ins.target)
                if loc is None:
                    self.stats['branches_unresolved_bank'] += 1
                    continue
                self._want(loc, 'call' if ins.flow in CALL_FLOWS else 'jump')
        for (b, _e), it in sorted(self.inline_adopt.items()):
            self._collect_inline(b, it)
        for b in range(self.nbanks):
            for r in self.regions[b]:
                if r.kind != 'ptrtable':
                    continue
                for i in range(0, r.size, 2):
                    if (b, r.start + i, 'word') in self.xref:
                        continue
                    v = self.rom[r.off + i] | (self.rom[r.off + i + 1] << 8)
                    if v == 0:
                        continue        # $0000 is far more likely a null/empty slot than a pointer to 00:0000 (xref word forces it)
                    loc = self.resolve_target(b, r, v)
                    if loc is not None:
                        self._want(loc, 'ptr')

    MACRO_NAMES = ('farcall', 'farcall_raw', 'FARCALL_FN')     # macros / EQUS of constants/macros.inc + ram.inc (one namespace with labels)

    def _check_macro_names(self):
        """With macros on, no label, constant or RAM name may be one of MACRO_NAMES: rgbasm keeps macros, EQUS and labels in one
        symbol namespace, so the clash would only surface later as an rgbasm error in every bank (found by the verifier)."""
        if not self.macros:
            return
        for b in range(self.nbanks):
            for s in self.cfg.symbols.get(b, ()):
                if s.name in self.MACRO_NAMES:
                    self.diag.error(s.loc, 'name %r collides with a farcall macro of constants/macros.inc (rename it or use --no-macros)' % s.name)
        for v in self.cfg.ram:
            if v.name in self.MACRO_NAMES:
                self.diag.error(v.loc, 'name %r collides with a farcall macro of constants/macros.inc (rename it or use --no-macros)' % v.name)

    def farcall_conv(self):
        """(convention, entry label name) of THE far call the `farcall` macros stand for, or None: macros are on, there
        is exactly one `farptr` convention in config/conventions.tsv and its entry has a label (the macro calls
        that label through the FARCALL_FN EQUS of ram.inc, so the name is never hard-coded)."""
        if self._fc is False:
            self._fc = None
            fcs = [c for c in self.cfg.conventions if c.layout == 'farptr']
            if self.macros and len(fcs) == 1:
                nm = self.name_at((fcs[0].bank, fcs[0].addr))
                if nm is not None and self.name_val.get(nm) == fcs[0].addr and fcs[0].bank == 0:
                    self._fc = (fcs[0], nm)
        return self._fc

    def far_loc(self, w: int, bb: int) -> Optional[Tuple[int, int]]:
        """ROM location (bank, address) a far pointer `dw w ; db bb` designates, or None when it does not name a
        ROM location: bank byte 0 = ROM0 (address must be < $4000), otherwise the address must lie in the window of
        ROM bank `bb` (a `$8000+` address selects a WRAM/SRAM bank, not a ROM bank).  Never a ramcode region: its
        ROM bytes run elsewhere and BANK() of a label inside a LOAD block is the RAM section's bank."""
        if bb >= self.nbanks:
            return None
        if bb == 0:
            if w >= 0x4000:
                return None
        elif not mtcfg.window(bb)[0] <= w < mtcfg.window(bb)[1]:
            return None
        r = self.region_at(bb, w)
        if r is None or r.kind == 'ramcode':
            return None
        return (bb, w)

    def _collect_inline(self, b: int, it: conv.InlineData):
        if it.conv.layout == 'farptr':
            loc = self.far_loc(it.word, it.raw[2])
            self.stats['inline_far_targets_unresolved' if loc is None else 'inline_far_targets'] += 1
            if loc is not None:
                self._want(loc, 'call')

    def _finalize_labels(self):
        for loc in sorted(self.want):
            tb, ta = loc
            if self.has_label(loc):
                continue
            r = self.region_at(tb, ta)
            kinds = self.want[loc]
            if r.kind in ('code', 'ramcode'):
                prefix = 'Function' if 'call' in kinds else 'Label'
            elif r.kind in ('words', 'ptrtable'):
                prefix = 'Table'
            elif r.kind == 'text':
                prefix = 'String'
            else:
                prefix = 'Data'
            name = '%s_%02X_%04X' % (prefix, tb, self.run_addr(tb, ta))
            self.add_label(tb, ta, name, 'generic', '')
            self.stats['generic_' + prefix] += 1
        self.diag.raise_if_errors()

    # ------------------------------------------------------------- operands
    def _hw_name(self, addr: int) -> Optional[Tuple[str, int]]:
        n = self.hw.io.get(addr)
        if n is not None:
            return n, addr
        if 0xFF30 < addr <= 0xFF3F and self.hw.io.get(0xFF30) == '_AUD3WAVERAM':
            return '_AUD3WAVERAM + %d' % (addr - 0xFF30), addr
        return None

    def _substitute(self, text: str, val: int, want: int, what: str) -> str:
        if val != want:
            raise GenError('internal: %s %s has value $%04X but the operand is $%04X' % (what, text, val, want))
        return text

    def render_insn(self, r: Region, sa: int, ins: sm83.Insn) -> str:
        b = r.bank
        st = self.stats

        def branch(t):
            x = self.xref.get((b, sa, 'branch'))
            if x is not None:
                loc = x[1]
            else:
                loc = self.resolve_target(b, r, t)
                if loc is None:
                    return None
            nm = self.name_at(loc)
            if nm is None:
                st['targets_unlabelled'] += 1
                return None
            st['branch_labels'] += 1
            return self._substitute(nm, self.name_val[nm], t, 'label')

        def imm16(v, kind):
            x = self.xref.get((b, sa, 'imm' if kind == 'imm' else 'mem'))
            if x is not None:
                if x[0] == 'ram':
                    st['xref_ram'] += 1
                    return self._substitute(x[1][0], x[1][1], v, 'ram name')
                nm = self.name_at(x[1])
                st['xref_labels'] += 1
                return self._substitute(nm, self.name_val[nm], v, 'label')
            if kind != 'mem':
                return None
            return self._mem_name(v, ins.fmt == 'ld [{i}], a')      # MBC names only for `ld [a16], a` (never `ld [a16], sp`)

        def hram(v):
            return self._mem_name(v, False, ldh=True)

        if ins.flow == 'rst':       # sm83 prints rst vectors numerically; use the label of the vector when there is one
            nm = branch(ins.target)
            return 'rst ' + nm if nm else ins.text()
        return ins.text(branch, imm16, hram)

    def _mem_name(self, addr: int, write: bool, ldh: bool = False) -> Optional[str]:
        st = self.stats
        if 0xFF00 <= addr <= 0xFF7F or addr == 0xFFFF:
            h = self._hw_name(addr)
            if h is not None:
                st['hw_names'] += 1
                return self._substitute(h[0], h[1], addr, 'hardware name')
        if write and not ldh and addr in self.hw.mbc:
            st['mbc_names'] += 1
            return self._substitute(self.hw.mbc[addr], addr, addr, 'MBC name')
        if addr >= 0x8000:
            e = self.ram_expr(addr)
            if e is not None:
                st['ram_names'] += 1
                return self._substitute(e[0], e[1], addr, 'ram name')
        return None

    def word_name(self, r: Region, addr: int, v: int) -> Optional[str]:
        """Symbol/label for a dw value in a words/ptrtable region (or None -> numeric)."""
        x = self.xref.get((r.bank, addr, 'word'))
        if x is not None:
            if x[0] == 'ram':
                return self._substitute(x[1][0], x[1][1], v, 'ram name')
            nm = self.name_at(x[1])
            return self._substitute(nm, self.name_val[nm], v, 'label')
        if v == 0:
            return None                 # never turn a null/empty slot into a label without an explicit xref word row
        loc = self.resolve_target(r.bank, r, v)
        if loc is None:
            return None
        nm = self.name_at(loc) if r.kind == 'ptrtable' else self.named_at(loc)
        if nm is None:
            return None
        self.stats['word_labels'] += 1
        return self._substitute(nm, self.name_val[nm], v, 'label')

    # ------------------------------------------------------------- line checks
    def _tok(self, t: str) -> int:
        t = t.strip()
        if t.startswith('$'):
            return int(t[1:], 16)
        m = re.fullmatch(r'BANK\(([A-Za-z_][A-Za-z0-9_]*)\)', t)
        if m:           # the ROM bank a label is stored in; only exact for labels outside LOAD blocks
            loc = self.name_loc.get(m.group(1))
            r = self.region_at(*loc) if loc and loc[0] not in ('const', 'ram') else None
            if r is None or r.kind == 'ramcode':
                raise GenError('internal: BANK(%s) is not a ROM label' % m.group(1))
            return loc[0]
        if t in self.name_val:
            return self.name_val[t]
        raise GenError('internal: cannot evaluate %r' % t)

    def verify_line(self, text: str, claim: bytes, absoff: int):
        text = text.split(' ;', 1)[0]
        if text.startswith('\tfarcall'):
            fc = self.farcall_conv()
            if fc is None:
                raise GenError('internal: %r without a far-call convention' % text)
            m = re.fullmatch(r'\tfarcall ([A-Za-z_][A-Za-z0-9_]*)', text)
            if m:
                args = [self._tok(m.group(1)), self._tok('BANK(%s)' % m.group(1))]
            else:
                m = re.fullmatch(r'\tfarcall_raw (\$[0-9A-F]{4}), (\$[0-9A-F]{2})', text)
                if not m:
                    raise GenError('internal: bad farcall line %r' % text)
                args = [self._tok(m.group(1)), self._tok(m.group(2))]
            got = b'\xCD' + fc[0].addr.to_bytes(2, 'little') + args[0].to_bytes(2, 'little') + bytes([args[1]])
        elif text.startswith('\tdb '):
            got = bytes(self._tok(t) for t in text[4:].split(','))
        elif text.startswith('\tdw '):
            got = b''.join(self._tok(t).to_bytes(2, 'little') for t in text[4:].split(','))
        elif text.startswith('\tds '):
            m = re.fullmatch(r'\tds \$([0-9A-F]+), \$([0-9A-F]{2})', text)
            if not m:
                raise GenError('internal: bad ds line %r' % text)
            got = bytes([int(m.group(2), 16)]) * int(m.group(1), 16)
        elif text.startswith('\tINCBIN '):
            m = re.fullmatch(r'\tINCBIN "([^"]+)", \$([0-9A-F]+), \$([0-9A-F]+)', text)
            if not m or m.group(1) != self.incbin:
                raise GenError('internal: bad INCBIN line %r' % text)
            off, n = int(m.group(2), 16), int(m.group(3), 16)
            if off != absoff:
                raise GenError('internal: INCBIN offset $%X but bank position is $%X' % (off, absoff))
            got = self.rom[off:off + n]
        else:
            return
        if got != claim:
            raise GenError('internal: line %r does not round-trip to the ROM bytes' % text)

    # ---------------------------------------------------------------- emission
    def _label_lines(self, out: BankOut, r: Region, addr: int):
        labs = self.labels[r.bank].get(addr)
        if not labs:
            return
        out.line('')
        cite = '%02X:%04X' % (r.bank, addr)
        if r.kind == 'ramcode':
            cite += ' (runs at $%04X)' % self.run_addr(r.bank, addr)
        for i, lab in enumerate(labs):
            out.line('%s::%s' % (lab.name, ' ; ' + cite if i == 0 else ''))

    def _segments(self, r: Region, extra=()) -> List[Tuple[int, int]]:
        la = self.label_addrs.get(r.bank)
        if la is None:
            la = sorted(self.labels[r.bank])
        lo = bisect.bisect_right(la, r.start)
        hi = bisect.bisect_left(la, r.end)
        pts = sorted({r.start, r.end, *la[lo:hi], *(e for e in extra if r.start < e < r.end)})
        return list(zip(pts, pts[1:]))

    def inline_lines(self, bank: int, it: conv.InlineData) -> List[Tuple[str, bytes]]:
        """(text, bytes) lines for the inline bytes after a convention call."""
        raw, lay = it.raw, it.conv.layout
        if lay == 'farptr':
            w, bb = it.word, raw[2]
            loc = self.far_loc(w, bb)
            nm = self.name_at(loc) if loc is not None else None
            if nm is not None:
                # a label at exactly (bank byte, address): rgbasm/rgblink compute both bytes, the compare proves them
                self._substitute(nm, self.name_val[nm], w, 'label')
                if self.name_loc[nm] != loc:
                    raise GenError('internal: label %s is at %s, not at the far pointer target %s' % (
                        nm, self.cite(*self.name_loc[nm]), self.cite(*loc)))
                self.stats['inline_far_labelled'] += 1
                return [('dw ' + nm, raw[:2]), ('db BANK(%s)' % nm, raw[2:3])]
            return [('dw ' + hexw(w), raw[:2]), ('db ' + hexb(bb), raw[2:3])]
        if lay == 'inline_dw':
            x = self.xref.get((bank, it.slot, 'word'))
            if x is not None:       # explicit `xref word` row: the analyst says which bank the word means
                if x[0] == 'ram':
                    return [('dw ' + self._substitute(x[1][0], x[1][1], it.word, 'ram name'), raw)]
                nm = self.name_at(x[1])
                return [('dw ' + self._substitute(nm, self.name_val[nm], it.word, 'label'), raw)]
            return [('dw ' + hexw(it.word), raw)]
        if lay == 'inline_db':
            return [('db ' + hexb(raw[0]), raw)]
        raise GenError('internal: unhandled inline layout %s' % lay)

    def _emit_db(self, out: BankOut, chunk: bytes):
        for i in range(0, len(chunk), 16):
            part = chunk[i:i + 16]
            out.emit('\tdb ' + ', '.join(hexb(x) for x in part), part)

    def _emit_words(self, out: BankOut, r: Region, a: int, z: int):
        per = 1 if r.kind == 'ptrtable' else 8
        vals = []
        for addr in range(a, z, 2):
            o = r.off + (addr - r.start)
            v = self.rom[o] | (self.rom[o + 1] << 8)
            vals.append((addr, v, self.word_name(r, addr, v) or hexw(v)))
        for i in range(0, len(vals), per):
            part = vals[i:i + per]
            claim = b''.join(v.to_bytes(2, 'little') for _, v, _ in part)
            out.emit('\tdw ' + ', '.join(t for _, _, t in part), claim)

    def _emit_region(self, out: BankOut, r: Region):
        hdr = '; ---- %s $%04X-$%04X (%d bytes)' % (r.kind, r.start, r.end, r.size)
        if r.gap:
            hdr += ' [unclassified gap]'
        else:
            if r.status:
                hdr += ' [%s]' % r.status
            if r.note:
                hdr += ' %s' % r.note
        out.line('')
        out.line(hdr)
        if r.kind in ('code', 'ramcode'):
            self._emit_code(out, r)
            return
        adopt = self.inline_adopt.get((r.bank, r.start)) if r.kind == 'data' else None
        if adopt is not None:
            out.line('; inline %s bytes of the convention call at %02X:%04X (config/conventions.tsv, docs/FORMATS.md)' % (
                adopt.conv.layout, r.bank, adopt.site))
        for a, z in self._segments(r, (r.start + adopt.length,) if adopt is not None else ()):
            self._label_lines(out, r, a)
            chunk = self.rom[r.off + (a - r.start):r.off + (z - r.start)]
            if adopt is not None and a == r.start:
                for txt, claim in self.inline_lines(r.bank, adopt):
                    out.emit('\t' + txt, claim)
                continue
            if r.kind == 'zero':
                out.emit('\tds $%X, $00' % len(chunk), chunk)
            elif r.kind == 'raw':
                absoff = out.bank * BANK_SIZE + out.pos
                out.emit('\tINCBIN "%s", $%X, $%X' % (self.incbin, absoff, len(chunk)), chunk)
            elif r.kind in ('data', 'text', 'gfx'):
                self._emit_db(out, chunk)
            elif r.kind in ('words', 'ptrtable'):
                self._emit_words(out, r, a, z)
            else:
                raise GenError('internal: unhandled kind %s' % r.kind)

    def _emit_code(self, out: BankOut, r: Region):
        if r.kind == 'ramcode':
            area = mtcfg.ram_area(r.runaddr, r.size)
            spec = '%s[$%04X]' % (area[2], r.runaddr)
            if r.runbank is not None:
                spec += ', BANK[%d]' % r.runbank
            un = self.union.get((r.bank, r.idx))
            if un:
                out.line('\tLOAD UNION "%s", %s' % (un, spec))
            else:
                out.line('\tLOAD "RAM_%02X_%04X", %s' % (r.bank, r.start, spec))
        items = self.insns[(r.bank, r.idx)]
        fc = self.farcall_conv()
        skip = -1
        for k, (sa, ins) in enumerate(items):
            if k == skip:
                continue
            if fc is not None and ins.flow == 'call' and k + 1 < len(items) and items[k + 1][1].flow == 'inline' \
                    and items[k + 1][1].conv is fc[0] and \
                    self.render_insn(r, sa, ins) == 'call ' + fc[1]:
                self._label_lines(out, r, sa)
                it = items[k + 1][1]
                lines = self.inline_lines(r.bank, it)
                if lines[1][0].startswith('db BANK(') and lines[0][0].startswith('dw ') and lines[0][0][3:] == lines[1][0][8:-1]:
                    txt = 'farcall ' + lines[0][0][3:]
                    self.stats['farcall_macro'] += 1
                else:
                    txt = 'farcall_raw %s, %s' % (lines[0][0][3:], lines[1][0][3:])
                    self.stats['farcall_raw_macro'] += 1
                out.emit('\t' + txt, ins.raw + it.raw)
                skip = k + 1
                continue
            if ins.flow == 'inline':
                for txt, claim in self.inline_lines(r.bank, ins):
                    out.emit('\t' + txt, claim)
                if items[k - 1][1].flow in TERMINATORS:      # inline bytes after a `jp`: the blank line comes after them
                    out.line('')
                continue
            self._label_lines(out, r, sa)
            txt = self.render_insn(r, sa, ins)
            if ins.flow == 'bad':
                txt += ' ; illegal opcode'
            out.emit('\t' + txt, ins.raw)
            if ins.flow in TERMINATORS and not (k + 1 < len(items) and items[k + 1][1].flow == 'inline'):
                out.line('')
        if r.kind == 'ramcode':
            out.line('\tENDL')

    def bank_source(self, b: int) -> str:
        out = BankOut(self, b)
        out.line(GENERATED_HEADER)
        out.line('; bank %02X' % b)
        out.line('')
        out.line('INCLUDE "constants/hardware.inc"')
        out.line('INCLUDE "ram.inc"')
        if self.farcall_conv() is not None:
            out.line('INCLUDE "constants/macros.inc"')
        cs = self.cfg.symbols.get(b, [])
        cs = [s for s in cs if s.type == 'const']
        if cs:
            out.line('')
            for s in cs:
                out.line('DEF %s EQU $%04X ; %s %s' % (s.name, s.addr, s.status, s.evidence))
                out.line('EXPORT %s' % s.name)
        out.line('')
        if b == 0:
            out.line('SECTION "Bank%02X", ROM0[$0000]' % b)
        else:
            out.line('SECTION "Bank%02X", ROMX[$4000], BANK[$%02X]' % (b, b))
        for r in self.regions[b]:
            self._emit_region(out, r)
        if out.pos != BANK_SIZE:
            raise GenError('internal: bank %02X emitted %d bytes instead of %d' % (b, out.pos, BANK_SIZE))
        return '\n'.join(out.lines).rstrip('\n') + '\n'

    def ram_inc(self) -> str:
        lines = [GENERATED_HEADER,
                 '; RAM / SRAM / HRAM variable names from config/ram/*.tsv (addresses only, no bytes).', '']
        for v in sorted(self.cfg.ram, key=lambda v: (v.addr, v.name)):
            lines.append('DEF %s EQU $%04X ; size %d %s %s %s' % (v.name, v.addr, v.size, v.type, v.status, v.evidence))
        fc = self.farcall_conv()
        if fc is not None:
            lines += ['', '; label of the far-call convention entry %02X:%04X (config/conventions.tsv); the farcall macros of' % (fc[0].bank, fc[0].addr),
                      '; constants/macros.inc call it through this EQUS', 'DEF FARCALL_FN EQUS "%s"' % fc[1]]
        return '\n'.join(lines).rstrip('\n') + '\n'

    def generate(self) -> Dict[str, str]:
        files = {'ram.inc': self.ram_inc()}
        for b in range(self.nbanks):
            files['bank%02x.asm' % b] = self.bank_source(b)
        return files


